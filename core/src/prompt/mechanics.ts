/**
 * Микро-правила по конкретным механикам.
 * Вставляются в промпт, если классификатор их нашёл.
 */
import type { Mechanic } from "../types.ts";

export const MECHANIC_RULES: Record<Mechanic, string> = {
  grow: "Механика: игрок/объект растёт при выполнении условия (еда, очки).",
  collect: "Механика: сбор предметов по карте, каждый = +счёт.",
  avoid: "Механика: избегание препятствий, столкновение = штраф/проигрыш.",
  jump: "Механика: прыжок с гравитацией и приземлением на платформы.",
  match: "Механика: сопоставление одинаковых элементов, исчезновение при совпадении.",
  tap: "Механика: тап/клик по элементу — основное действие.",
  drag: "Механика: перетаскивание элементов (touch + mouse).",
  swipe: "Механика: свайпы по 4 направлениям (touch).",
  combo: "Механика: комбо-серии увеличивают множитель очков.",
  timer: "Механика: ограничение по времени на раунд, виден таймер.",
  levels: "Механика: минимум 3 уровня с растущей сложностью.",
  upgrade: "Механика: апгрейды, покупаемые за игровой ресурс.",
  score: "Механика: счёт отображается крупно в углу, сохраняется в localStorage.",
  lives: "Механика: у игрока N жизней, потеря всех = game over.",
};

export function mechanicsBlock(mechanics: Mechanic[]): string {
  if (mechanics.length === 0) return "";
  const lines = mechanics.map((m) => "- " + MECHANIC_RULES[m]);
  return `МЕХАНИКИ:\n${lines.join("\n")}`;
}
