export function genreRule(genre: Genre): string {
  if (genre === "unknown") {
    return `ЖАНР: не определён явно. Выбери самый подходящий по промпту
(аркада, головоломка, кликер, платформер) и реализуй его целиком.`;
  }
  return GENRE_RULES[genre];
}
